def slug(s: str) -> str:
    """Simple slugify for muscle/equipment/exercise names."""
    return (
        s.lower()
        .replace("&", "and")
        .replace("/", " ")
        .replace("(", " ")
        .replace(")", " ")
        .replace(",", " ")
        .replace("  ", " ")
        .strip()
        .replace(" ", "_")
    )
